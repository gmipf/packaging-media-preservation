"""unscrambler (a DiscImageCreator helper): read the command line out of the
source, render a bash completion.

main() in unscrambler.c reads three positionals: the input it opens for
reading, the output it opens for writing, and a type number it range-checks.
"""
import re

import clex

FILES = ["unscrambler.c"]

SMOKE = [
    ("{cmd} a b ", {"0", "5"}, set()),
    ("{cmd} a b 0 ", set(), "*"),
]


class ParseError(Exception):
    pass


def die(msg):
    raise ParseError(f"unscrambler: {msg}")


def extract(src):
    try:
        body = clex.function_body(src["unscrambler.c"], "main")
    except clex.CError as e:
        die(str(e))
    need = re.search(r"if\s*\(\s*argc\s*<\s*(\d+)\s*\)", body)
    rd = re.search(r'fopen\(argv\[(\d)\],\s*"rb"\)', body)
    wr = re.search(r'fopen\(argv\[(\d)\],\s*"wb"\)', body)
    ty = re.search(r"type = strtoul\(argv\[(\d)\]", body)
    top = re.search(r"else if \(type > (\d+)\)", body)
    if not (need and rd and wr and ty and top):
        die("main() no longer reads input, output and type the way the generator knows")
    order = [int(rd.group(1)), int(wr.group(1)), int(ty.group(1))]
    if order != [1, 2, 3] or int(need.group(1)) != 4:
        die(f"argument positions moved: {order}, argc < {need.group(1)}")
    ext = re.search(r"input: \.(\w+) file", clex.c_strings(body))
    if not ext:
        die("the usage text no longer names the input's extension")
    return {"input_ext": ext.group(1), "types": [str(t) for t in range(int(top.group(1)) + 1)]}


def render(model, cmd, origin, names):
    fn = "_mediapres_" + re.sub(r"[^A-Za-z0-9]", "_", cmd)
    title = f"# bash completion for {cmd}".ljust(64) + "-*- shell-script -*-"
    return f"""{title}
# shellcheck shell=bash
#
# GENERATED by scripts/completions/gen.py from {origin}.
# Do not edit: change the generator, then run `scripts/completions/gen.py write`.
#
# {cmd} (installed with DiscImageCreator): <input .{model["input_ext"]}> <output> <type>

{fn}()
{{
    # shellcheck disable=SC2034  # words is filled in by _init_completion
    local cur prev words cword
    _init_completion || return

    case $cword in
        1) _filedir {model["input_ext"]} ;;
        2) _filedir ;;
        3) mapfile -t COMPREPLY < <(compgen -W '{" ".join(model["types"])}' -- "$cur") ;;
    esac
}} &&
    complete -F {fn} {" ".join(names)}

# ex: filetype=sh
"""
