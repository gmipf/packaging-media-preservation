"""dreamdump: read the command line out of the source, render a bash completion.

dreamdump reads os.Args itself (cli/option_parser.go): a flag is matched by
HasArgumentString("x") == the literal word --x, a value only by
FindArgumentString("x") == the word --x=VALUE. `--x VALUE` is silently ignored,
so only the '=' form is offered. The command is os.Args[1].
"""
import re

FILES = ["cli/option_parser.go", "cli/command_executor.go", "main.go"]

KINDS = {"drive": "device", "image-path": "dir"}

SMOKE = [
    ("{cmd} ", {"disc", "split"}, set()),
    ("{cmd} disc --", {"--drive=", "--image-path=", "--force-qtoc", "--read-at-once="}, set()),
    ("{cmd} disc --sector-order=", {"DATA_C2_SUB"}, set()),
    ("{cmd} disc --drive ", set(), "*"),
]


class ParseError(Exception):
    pass


def die(msg):
    raise ParseError(f"dreamdump: {msg}")


def extract(src):
    op, ce, mn = src["cli/option_parser.go"], src["cli/command_executor.go"], src["main.go"]
    flags = re.findall(r'HasArgumentString\("([a-z0-9-]+)"\)', op)
    values = re.findall(r'FindArgumentString\("([a-z0-9-]+)"\)', op)
    commands = re.findall(r'Name:\s*"([a-z0-9-]+)"', ce)
    if not set(KINDS) <= set(values) or len(flags) < 2 or not {"disc", "split"} <= set(commands):
        die(f"parse looks wrong: flags={flags} values={values} commands={commands}")
    if "os.Args[1]" not in ce:
        die("the command is no longer os.Args[1]")
    if 'strings.Split(arg, "=")' not in op:
        die("value syntax changed (no longer --key=value)")
    sw = re.search(r"func parseSectorOrder\(sectorOrder string\) int \{(.*?)\n\}", op, re.S)
    if not sw:
        die("parseSectorOrder not found")
    orders = re.findall(r'case "([A-Z0-9_]+)":', sw.group(1))
    if len(orders) < 2 or "sector-order" not in values:
        die(f"sector orders not found: {orders}")
    um = re.search(r'os\.Args\[0\] \+ " <([^>]+)> \[([^\]]*)\]', mn)
    if not um:
        die("usage line not found in main.go")
    doc = set(re.findall(r"--([a-z0-9-]+)", um.group(2))) | set(um.group(1).split(","))
    hidden = [x for x in commands if x not in doc] + ["--" + x for x in flags + values if x not in doc]
    return {"flags": flags, "values": values, "commands": commands, "orders": orders, "hidden": hidden}


def render(model, cmd, origin):
    fn = "_mediapres_" + re.sub(r"[^A-Za-z0-9]", "_", cmd)
    words = " ".join(["--" + f for f in model["flags"]] + ["--" + v + "=" for v in model["values"]])
    return f"""# bash completion for {cmd}                                  -*- shell-script -*-
# shellcheck shell=bash
#
# GENERATED by scripts/completions/gen.py from {origin}.
# Do not edit: change the generator, then run `scripts/completions/gen.py write`.
#
# dreamdump reads a value only as --option=VALUE (`--option VALUE` is ignored),
# so only that form is offered. Not in its usage line: {" ".join(model["hidden"]) or "-"}

{fn}()
{{
    # shellcheck disable=SC2034  # words is filled in by _init_completion
    local cur prev words cword split
    _init_completion -s || return

    if $split; then
        case $prev in
            --drive)
                local d
                COMPREPLY=()
                for d in /dev/sr[0-9]*; do
                    [[ -e $d && $d == "$cur"* ]] && COMPREPLY+=("$d")
                done
                ((${{#COMPREPLY[@]}})) || _filedir
                ;;
            --image-path)
                _filedir -d
                ;;
            --sector-order)
                mapfile -t COMPREPLY < <(compgen -W '{" ".join(model["orders"])}' -- "$cur")
                ;;
        esac
        return
    fi

    if [[ $cur == -* ]]; then
        mapfile -t COMPREPLY < <(compgen -W '{words}' -- "$cur")
        [[ ${{COMPREPLY-}} == *= ]] && compopt -o nospace
        return
    fi
    # the command must be the first argument
    ((cword == 1)) && mapfile -t COMPREPLY < <(compgen -W '{" ".join(model["commands"])}' -- "$cur")
}} &&
    complete -F {fn} {cmd}

# ex: filetype=sh
"""
