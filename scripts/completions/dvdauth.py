"""DVDAuth (installed as dvdauth, a DiscImageCreator helper): read the command
line out of the source, render a bash completion.

main() in DVDAuth.cpp needs exactly three positionals: the drive (on Linux a
device path it opens), the protection type, and the log file it writes.
"""
import re

import clex

FILES = ["DVDAuth/DVDAuth.cpp"]

SMOKE = [
    ("{cmd} d ", {"css", "cppm", "cprm"}, set()),
    ("{cmd} d css f ", set(), "*"),
]


class ParseError(Exception):
    pass


def die(msg):
    raise ParseError(f"DVDAuth: {msg}")


def extract(src):
    try:
        body = clex.function_body(src["DVDAuth/DVDAuth.cpp"], "main")
    except clex.CError as e:
        die(str(e))
    if not re.search(r"if \(argc == 4\)", body):
        die("main() no longer requires exactly three arguments")
    if not re.search(r"#elif __linux__\s+device\.hDevice = open\(argv\[1\],", body):
        die("on Linux the first argument is no longer the device path it opens")
    if not re.search(r'fopen\(argv\[3\], "w"\)', body):
        die("the third argument is no longer the file it writes")
    types = list(dict.fromkeys(re.findall(r'strncmp\(argv\[2\], "(\w+)", \d+\)', body)))
    usage = re.search(r"Usage: \S+ <(\w+)> <(\w+)> <(\w+)>", clex.c_strings(body))
    if len(types) < 2 or not usage:
        die(f"protection types or usage line not found: {types}")
    return {"types": types}


def render(model, cmd, origin, names):
    fn = "_mediapres_" + re.sub(r"[^A-Za-z0-9]", "_", cmd)
    title = f"# bash completion for {cmd}".ljust(64) + "-*- shell-script -*-"
    return f"""{title}
# shellcheck shell=bash
#
# GENERATED by scripts/completions/gen.py from {origin}.
# Do not edit: change the generator, then run `scripts/completions/gen.py write`.
#
# {cmd} (DVDAuth, installed with DiscImageCreator): <drive> <type> <log file>

{fn}()
{{
    # shellcheck disable=SC2034  # words is filled in by _init_completion
    local cur prev words cword
    _init_completion || return

    case $cword in
        1)
            local d
            COMPREPLY=()
            for d in /dev/sr[0-9]*; do
                [[ -e $d && $d == "$cur"* ]] && COMPREPLY+=("$d")
            done
            ((${{#COMPREPLY[@]}})) || _filedir
            ;;
        2) mapfile -t COMPREPLY < <(compgen -W '{" ".join(model["types"])}' -- "$cur") ;;
        3) _filedir ;;
    esac
}} &&
    complete -F {fn} {" ".join(names)}

# ex: filetype=sh
"""
