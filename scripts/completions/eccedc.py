"""EccEdc (installed as eccedc, a DiscImageCreator helper): read the command
line out of the source, render a bash completion.

checkArg() in EccEdc.cpp takes argv[1] as the sub-command and an exact argument
count per sub-command. The Linux build is what counts (checkex is Windows only).
printUsage()'s Linux branch names the positionals.
"""
import re

import clex

FILES = ["EccEdc/EccEdc.cpp"]

POSITIONAL_KINDS = [
    (r"Type", "type"),
    (r"(In|InOut|Out)FileName", "file"),
    (r"Minute|Second|Frame|Mode|CreateSectorNum|startLBA|endLBA", "int"),
]

SMOKE = [
    ("{cmd} ", {"check", "fix", "write"}, {"checkex"}),
    ("{cmd} check ", {"TOC", "Sub"}, set()),
    ("{cmd} fix TOC f ", set(), "*"),
    ("{cmd} write f ", set(), "*"),
    ("{cmd} check TOC f x ", set(), "*"),
]


class ParseError(Exception):
    pass


def die(msg):
    raise ParseError(f"EccEdc: {msg}")


def extract(src):
    cpp = src["EccEdc/EccEdc.cpp"]
    try:
        body = clex.linux_view(clex.function_body(cpp, "checkArg"))
        usage = clex.c_strings(clex.linux_view(clex.function_body(cpp, "printUsage")))
    except clex.CError as e:
        die(str(e))
    argc = {}
    for n, sub in re.findall(r'argc == (\d+) && \(!strcmp\(argv\[1\], "(\w+)"\)\)', body):
        argc[sub] = max(argc.get(sub, 0), int(n))
    if len(argc) < 3:
        die(f"sub-commands not found in checkArg(): {argc}")
    types = list(dict.fromkeys(re.findall(r'strncmp\(pszType, "(\w+)", \d+\)', cpp)))
    if len(types) < 2:
        die(f"the <Type> values are not found: {types}")
    lines = usage.split("\n")
    if "Usage" not in lines:
        die("printUsage() no longer starts with 'Usage'")
    names = {}
    for line in lines[lines.index("Usage") + 1:]:
        if not line.startswith("\t"):
            break
        m = re.match(r"\t(\w+) (.*)$", line)
        if m:
            got = re.findall(r"<([^>]+)>", m.group(2))
            if len(got) > len(names.get(m.group(1), [])):
                names[m.group(1)] = got
    subs = {}
    for sub, n in argc.items():
        if sub not in names:
            die(f"{sub} is not in the usage text: the generator does not know its positionals")
        if len(names[sub]) != n - 2:
            die(f"{sub}: the usage names {len(names[sub])} arguments, the parser reads {n - 2}")
        kinds = []
        for name in names[sub]:
            for rx, kind in POSITIONAL_KINDS:
                if re.fullmatch(rx, name):
                    kinds.append(kind)
                    break
            else:
                die(f"<{name}> of {sub}: the generator does not know what it is")
        subs[sub] = kinds
    for sub in names:
        if sub not in subs:
            die(f"the usage lists {sub}, the Linux parser does not accept it")
    return {"subs": subs, "types": types}


def render(model, cmd, origin, names):
    fn = "_mediapres_" + re.sub(r"[^A-Za-z0-9]", "_", cmd)
    arms = {}
    for sub, kinds in model["subs"].items():
        arms.setdefault(tuple(kinds), []).append(sub)
    case = "\n".join(f"        {' | '.join(s)}) kinds=({' '.join(k)}) ;;" for k, s in arms.items())
    title = f"# bash completion for {cmd}".ljust(64) + "-*- shell-script -*-"
    return f"""{title}
# shellcheck shell=bash
#
# GENERATED by scripts/completions/gen.py from {origin}.
# Do not edit: change the generator, then run `scripts/completions/gen.py write`.
#
# {cmd} (EccEdc, installed with DiscImageCreator) takes a sub-command and an
# exact number of arguments.

{fn}()
{{
    # shellcheck disable=SC2034  # words is filled in by _init_completion
    local cur prev words cword
    _init_completion || return

    if ((cword == 1)); then
        mapfile -t COMPREPLY < <(compgen -W '{" ".join(model["subs"])}' -- "$cur")
        return
    fi
    local -a kinds
    case ${{words[1]}} in
{case}
        *) return ;;
    esac
    local n=$((cword - 2))
    ((n < ${{#kinds[@]}})) || return
    case ${{kinds[n]}} in
        type) mapfile -t COMPREPLY < <(compgen -W '{" ".join(model["types"])}' -- "$cur") ;;
        file) _filedir ;;
    esac
}} &&
    complete -F {fn} {" ".join(names)}

# ex: filetype=sh
"""
